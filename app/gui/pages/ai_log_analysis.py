    def run_analysis():
        if running["value"]:
            return

        log_text = log_input.get("1.0", "end-1c").strip()
        if not log_text:
            status_label.configure(text="Paste or import a log first!", text_color=colors["accent"])
            return

        # Detect mode
        from app.hardware.ai_analyzer import detect_log_type
        selected_mode = mode_var.get()
        if selected_mode == "auto":
            selected_mode = detect_log_type(log_text)
            detected_label.configure(text=f"Detected: {selected_mode.upper()} log")

        # Determine backend
        selected_backend = backend_var.get()
        if selected_backend.startswith("auto"):
            selected_backend = "auto"

        # Check if selected backend is available
        if selected_backend == "groq":
            key = load_api_key()
            if not key or not key.startswith("gsk_"):
                status_label.configure(
                    text="Groq API key not found! Add key in config/groq_api_key.txt, or use 'auto' to fallback.",
                    text_color=colors["accent"],
                )
                return

        running["value"] = True
        analyze_btn.configure(state="disabled", text="  Analyzing...  ")
        progress.set(0)
        _clear_results()

        def do_analysis():
            # Animate progress bar
            step = [0]
            def tick_progress():
                if running["value"] and step[0] < 90:
                    step[0] += 2
                    try:
                        progress.set(step[0] / 100)
                    except Exception:
                        pass
                    try:
                        app.content.after(300, tick_progress)
                    except Exception:
                        pass
            try:
                app.content.after(0, tick_progress)
            except Exception:
                pass

            def update_status(msg):
                try:
                    app.content.after(0, lambda: status_label.configure(
                        text=msg, text_color=colors["info"]))
                except Exception:
                    pass

            # Build context from tool's own detection (if raw log was from UART scan)
            detected_ctx = ""
            if _is_processed_report(log_text):
                detected_ctx = _extract_raw_log_from_report(log_text)
            elif selected_mode == "boot":
                # Try to run quick parse on the log for context
                try:
                    from app.hardware.device_detector import DeviceAutoDetector
                    _det = DeviceAutoDetector.__new__(DeviceAutoDetector)
                    _parsed = _det._parse_boot_data(log_text.encode("utf-8", errors="replace"))
                    ctx_parts = []
                    if "chipset" in _parsed:
                        ctx_parts.append(f"Chipset: {_parsed['chipset']} ({_parsed.get('chipset_detail', '')})")
                    if "pmic_model" in _parsed:
                        ctx_parts.append(f"PMIC: {_parsed['pmic_model']}")
                    for k in sorted(_parsed.keys()):
                        if k.startswith("i2c_error"):
                            ctx_parts.append(f"I2C Error: {_parsed[k]}")
                    ic_probes = _parsed.get("ic_probes_failed", [])
                    if ic_probes:
                        ctx_parts.append(f"IC Probes Failed: {', '.join(ic_probes)}")
                    correlated = _parsed.get("correlated_faults", [])
                    for cf in correlated:
                        ctx_parts.append(f"CORRELATED: {cf['title']} ({cf['confidence']}%) — {cf['root_cause']}")
                    voltage_rails = _parsed.get("voltage_rails", {})
                    if voltage_rails:
                        ctx_parts.append("Voltages: " + ", ".join(f"{r}={uv/1000:.0f}mV" for r, uv in voltage_rails.items()))
                    if _parsed.get("boot_stuck"):
                        ctx_parts.append(f"BOOT STUCK at {_parsed.get('boot_stuck_stage', '?')}: {_parsed.get('boot_stuck_reason', '?')}")
                    if ctx_parts:
                        detected_ctx = "\n".join(ctx_parts)
                except Exception:
                    pass

            # Use FallbackAnalyzer for automatic fallback chain
            if app._ai_fallback is None:
                app._ai_fallback = FallbackAnalyzer()
            result, backend_used, backend_display = app._ai_fallback.analyze_with_status(
                log_text, mode=selected_mode, callback=update_status,
                detected_context=detected_ctx, backend=selected_backend,
            )

            def show_result():
                running["value"] = False
                progress.set(1.0)
                analyze_btn.configure(state="normal", text="  Analyze with AI  ")

                if result.success and result.parsed:
                    render_result(result.parsed, result.tokens_used)
                    token_text = f"Tokens: {result.tokens_used:,}" if result.tokens_used else "Local analysis"
                    tokens_label.configure(text=f"{token_text} | Backend: {backend_display}")
                    status_label.configure(
                        text=f"Analysis complete via {backend_display} ({selected_mode.upper()} mode)",
                        text_color=colors["success"],
                    )
                else:
                    _clear_results()
                    _append("ANALYSIS FAILED\n\n", "error")
                    _append(f"{result.error}\n\n", None)
                    if result.raw_response:
                        _append("Raw AI Response:\n", "dim")
                        _append(result.raw_response + "\n", "dim")
                    status_label.configure(
                        text=f"Failed: {result.error[:80]}",
                        text_color=colors["accent"],
                    )

            try:
                app.content.after(0, show_result)
            except Exception:
                pass

        threading.Thread(target=do_analysis, daemon=True).start()

