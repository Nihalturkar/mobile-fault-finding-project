def _is_processed_report(text: str) -> bool:
    """Check if text is a processed report (not raw boot log)."""
    markers = [
        "MOOXY AI FAULT DETECTOR",
        "HARDWARE DETECTION REPORT",
        "═══ PHASE",
        "BOOT THE PHONE NOW",
        "FAULT PATTERN MATCHING",
        "Hardware Health Check",
        "DETAILED COMPONENT REPORT",
        "Report generated by Mooxy AI Fault Detector",
    ]
    count = sum(1 for m in markers if m in text[:3000])
    return count >= 2


def _extract_raw_log_from_report(report_text: str) -> str:
    """Extract meaningful log data from a processed report for AI analysis.

    Instead of feeding the AI our own formatted report (which it can't parse
    well), we extract the actual boot log evidence, fault lines, and hardware
    status so the AI gets useful diagnostic data to work with.
    """
    lines = report_text.split("\n")
    extracted = []

    # Patterns that contain actual device/boot data worth analyzing
    useful_patterns = [
        "Chipset:", "Brand:", "Boot Stage:", "Version:", "Storage:",
        "Board:", "CPU Cores:", "Abnormal Boot:", "Boot Reason:",
        "Kernel Entry:", "RAM:", "MTK Chip",
        "PMIC", "PWRAP", "PLL", "SPM", "ATF", "BL31", "TrustZone",
        "EMI", "DRAM", "MTEST", "Watchdog", "RGU",
        "MTCMOS", "SPMI",
        # Actual boot log evidence lines
        "[I2C]", "[ATF]", "[SEC_POLICY]", "[SBC]", "[PART]", "[RGU]",
        "[LOG]", "Boot Log Error",
        "PL fatal", "cert verify", "cert chain",
        "transfer error", "fails,ret=",
        "recalibration", "dvfsrc", "hl7593",
        # Status data
        "Evidence:", "Status:", "PASS", "FAIL",
        "Init Time:", "rdata=",
        # Fault info
        "WARNING:", "CRITICAL:", "Problem:", "Component:",
        "Causes:", "Check:", "Fix:", "Parts:", "Difficulty:",
    ]

    # Skip purely decorative/filler lines
    skip_patterns = [
        "═══ PHASE", "BOOT THE PHONE NOW", "Opening FTDI",
        "Connected!", "Listening for", "This captures preloader",
        ">>> BOOT THE PHONE", "Report generated by",
        "MOOXY AI FAULT DETECTOR", "HARDWARE DETECTION REPORT",
        "bytes captured", "bytes received", "Analyzing boot data",
        "Running AI Rule Engine", "Loaded ", "fault rules",
        "No known fault patterns", "Detection complete",
        "═══════════", "──────", "======",
        "DETAILED COMPONENT REPORT", "FAULT ANALYSIS",
        "AI FAULT PATTERN MATCHING",
    ]

    for line in lines:
        stripped = line.strip()
        if not stripped:
            continue

        # Skip decorative/filler
        if any(p in stripped for p in skip_patterns):
            continue

        # Skip lines that are all decoration characters
        if all(c in "═─━─=─-_*● " for c in stripped):
            continue

        # Keep lines with useful diagnostic data
        if any(p in stripped for p in useful_patterns):
            extracted.append(stripped)
        # Keep lines with boot log content markers
        elif stripped.startswith(("✅", "❌", "⚠️", "⚪", "🔴", "🟡", "🟠")):
            extracted.append(stripped)
        # Keep fault detail lines
        elif stripped.startswith(("→", "•", "✓")):
            extracted.append(stripped)

    if not extracted:
        return ""

    return "\n".join(extracted)


