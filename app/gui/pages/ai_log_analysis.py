    def _status_tag(status):
        s = str(status).lower()
        if s in ("success", "ok", "normal", "pass"):
            return "ok"
        if s in ("warning", "warn", "caution"):
            return "warning"
        if s in ("error", "failed", "fail", "critical", "panic"):
            return "error"
        return "info"

    def _status_icon(status):
        s = str(status).lower()
        if s in ("success", "ok", "normal", "pass"):
            return "[OK]"
        if s in ("warning", "warn", "caution"):
            return "[!!]"
        if s in ("error", "failed", "fail", "critical", "panic"):
            return "[XX]"
        return "[--]"

    def _confidence_bar(level):
        l = str(level).lower()
        if l == "high":
            return "Confidence: [========] HIGH"
        if l == "medium":
            return "Confidence: [=====   ] MEDIUM"
        return "Confidence: [==      ] LOW"

    # ── Render parsed result ─────────────────────────────────────────────
    def render_result(parsed, tokens=0):
        _clear_results()

        mode = parsed.get("analysis_mode", "boot")

        # ══════════════════════════════════════════════
        #  SMART AI REPORT — problem first, details later
        # ══════════════════════════════════════════════

        # ── Conclusion (always show) ───
        conclusion = parsed.get("conclusion", {})
        if conclusion:
            status = conclusion.get("status", "info")

            if status in ("needs_repair", "critical"):
                _append("=" * 55 + "\n", "dim")
                _append(f"  🔴 PROBLEM: {conclusion.get('verdict', 'Issue detected')}\n", "error")
                _append("=" * 55 + "\n", "dim")
            elif status in ("minor_issues", "warning"):
                _append(f"  🟡 {conclusion.get('verdict', 'Minor issues found')}\n", "warning")
            else:
                _append(f"  ✅ {conclusion.get('verdict', 'No issues found')}\n", "ok")

            reasoning = conclusion.get("reasoning", "")
            if reasoning:
                _append(f"  {reasoning}\n\n", None)

            health_pct = conclusion.get("health_percent")
            if health_pct is not None and health_pct < 90:
                _append(f"  Health: {health_pct}%\n", _status_tag(status))
            _append(f"\n  {conclusion.get('reasoning', '')}\n\n", None)

        # ── Summary Cards ───
        cards = parsed.get("summary_cards", [])
        if cards:
            _append("-" * 70 + "\n", "dim")
            _append("  SUMMARY\n", "section")
