def generate_ai_report(matches: list[MatchedFault]) -> str:
    """Produce a formatted text report of all matched faults."""
    if not matches:
        return (
            "========================================\n"
            "  DIAGNOSTIC REPORT — NO FAULTS FOUND\n"
            "========================================\n\n"
            "No known fault patterns were detected in the provided diagnostic data.\n"
            "This does not guarantee the device is fault-free — only that no\n"
            "patterns in the current rule database matched.\n"
        )

    lines: list[str] = []
    lines.append("=" * 72)
    lines.append("  MOBILE REPAIR DIAGNOSTIC REPORT")
    lines.append(f"  Generated: {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}")
    lines.append(f"  Total faults detected: {len(matches)}")

    critical = sum(1 for m in matches if m.rule.severity == "critical")
    warning = sum(1 for m in matches if m.rule.severity == "warning")
    info = sum(1 for m in matches if m.rule.severity == "info")

    lines.append(f"  Critical: {critical}  |  Warning: {warning}  |  Info: {info}")
    lines.append("=" * 72)
    lines.append("")

    for idx, mf in enumerate(matches, 1):
        r = mf.rule
        sev_icon = {"critical": "[!!!]", "warning": "[!!]", "info": "[i]"}.get(
            r.severity, "[?]"
        )
        lines.append(f"--- Fault #{idx} {sev_icon} {r.fault_name} ---")
        lines.append(f"  Rule ID       : {r.rule_id}")
        lines.append(f"  Category      : {r.category}")
        lines.append(f"  Severity      : {r.severity.upper()}")
        lines.append(f"  Confidence    : {mf.confidence * 100:.0f}%")
        lines.append(f"  Component     : {r.component}")
        lines.append(f"  Chipset       : {r.chipset_specific}")
        lines.append(f"  Difficulty    : {r.difficulty}")
        lines.append(f"  Source        : {mf.source}")
        if mf.timestamp:
            lines.append(f"  Timestamp     : {mf.timestamp}")
        lines.append(f"  Matched Text  : {mf.matched_text[:200]}")
        lines.append("")
        lines.append(f"  Description:")
        lines.append(f"    {r.description}")
        lines.append("")
        lines.append(f"  Possible Causes:")
        for c in r.possible_causes:
            lines.append(f"    - {c}")
        lines.append("")
        lines.append(f"  Diagnostic Steps:")
        for i, s in enumerate(r.diagnostic_steps, 1):
            lines.append(f"    {i}. {s}")
        lines.append("")
        lines.append(f"  Repair Steps:")
        for i, s in enumerate(r.repair_steps, 1):
            lines.append(f"    {i}. {s}")
        lines.append("")
        if r.parts_needed:
            lines.append(f"  Parts Needed:")
            for p in r.parts_needed:
                lines.append(f"    * {p}")
            lines.append("")
        lines.append("-" * 72)
        lines.append("")

    # Summary table
    lines.append("=" * 72)
    lines.append("  SUMMARY TABLE")
    lines.append("=" * 72)
    lines.append(f"  {'#':<4} {'Severity':<10} {'Confidence':<12} {'Category':<12} {'Fault Name'}")
    lines.append(f"  {'-'*4} {'-'*10} {'-'*12} {'-'*12} {'-'*30}")
    for idx, mf in enumerate(matches, 1):
        lines.append(
            f"  {idx:<4} {mf.rule.severity.upper():<10} {mf.confidence*100:>6.0f}%     "
            f"{mf.rule.category:<12} {mf.rule.fault_name}"
        )
    lines.append("")

    # Parts shopping list
    all_parts: list[str] = []
    for mf in matches:
        for p in mf.rule.parts_needed:
            if p not in all_parts:
                all_parts.append(p)
    if all_parts:
        lines.append("=" * 72)
        lines.append("  PARTS SHOPPING LIST")
        lines.append("=" * 72)
        for p in all_parts:
            lines.append(f"  [ ] {p}")
        lines.append("")

    lines.append("=" * 72)
    lines.append("  END OF REPORT")
    lines.append("=" * 72)
    return "\n".join(lines)
