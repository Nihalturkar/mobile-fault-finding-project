@dataclass
class FaultRule:
    rule_id: str
    category: str
    severity: str
    pattern: str
    pattern_source: str
    fault_name: str
    component: str
    description: str
    possible_causes: list
    diagnostic_steps: list
    repair_steps: list
    parts_needed: list
    difficulty: str
    confidence: float
    chipset_specific: str


@dataclass
class MatchedFault:
    rule: FaultRule
    matched_text: str
    source: str
    timestamp: str
    confidence: float


