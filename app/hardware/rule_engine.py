class RuleEngine:
    """Matches diagnostic data against known fault patterns."""

    def __init__(self):
        self.rules = self._load_rules()
        # Pre-compile all regex patterns once at init time
        self._compiled_patterns: dict[str, re.Pattern] = {}
        for rule in self.rules:
            if rule.rule_id not in self._compiled_patterns:
                self._compiled_patterns[rule.rule_id] = re.compile(
                    rule.pattern, re.IGNORECASE | re.MULTILINE
                )

    @staticmethod
    def _load_rules() -> list[FaultRule]:
        return FAULT_RULES

    # ----- public API -----

    def analyze(
        self,
        logcat_text: str = "",
        thermal_text: str = "",
        dmesg_text: str = "",
        battery_data: str = "",
        adb_result: str = "",
    ) -> list[MatchedFault]:
        """Run all rules against all data sources and return sorted matches."""
        matches: list[MatchedFault] = []
        sources = {
            "logcat": logcat_text or "",
            "thermal": thermal_text or "",
            "dmesg": dmesg_text or "",
            "battery": battery_data if isinstance(battery_data, str) else str(battery_data),
            "dumpsys": adb_result or "",
        }

        for rule in self.rules:
            target_sources = (
                sources.items()
                if rule.pattern_source == "any"
                else [(rule.pattern_source, sources.get(rule.pattern_source, ""))]
            )
            for source_name, text in target_sources:
                if not text:
                    continue
                for m in self._compiled_patterns[rule.rule_id].finditer(text):
                    matched_line = _extract_line(text, m.start())

                    # Context filtering — skip false positives
                    line_lower = matched_line.lower()
                    # If the matched line indicates SUCCESS, skip it
                    if self._is_false_positive(line_lower, rule):
                        continue

                    ts = _extract_timestamp(matched_line)
                    confidence = self._adjust_confidence(rule, matched_line, source_name)
                    matches.append(
                        MatchedFault(
                            rule=rule,
                            matched_text=matched_line.strip(),
                            source=source_name,
                            timestamp=ts,
                            confidence=confidence,
                        )
                    )
                    break  # one match per rule per source is enough

        # Sort: critical first, then by confidence descending
        severity_order = {"critical": 0, "warning": 1, "info": 2}
        matches.sort(
            key=lambda mf: (severity_order.get(mf.rule.severity, 3), -mf.confidence)
        )
        return matches

    def analyze_logcat(self, text: str) -> list[MatchedFault]:
        return self.analyze(logcat_text=text)

    def analyze_thermal(self, text: str) -> list[MatchedFault]:
        return self.analyze(thermal_text=text)

    def analyze_dmesg(self, text: str) -> list[MatchedFault]:
        return self.analyze(dmesg_text=text)

    def analyze_battery(self, data: str) -> list[MatchedFault]:
        return self.analyze(battery_data=data)

    # ----- confidence adjustment -----

    @staticmethod
    @staticmethod
    def _is_false_positive(line_lower: str, rule: FaultRule) -> bool:
        """Check if a matched line is actually a false positive (OK status, not error)."""
        # If the line contains strong positive indicators, it's likely NOT a fault
        positive_indicators = [
            "status: ok", "✅", "pass", "done", "success", "normal",
            "init done", "init ok", "calibrated", "ready",
            "evidence:", "status:", "healthy",  # Our own report lines
            "detailed component report",  # Our report headers
        ]
        if any(p in line_lower for p in positive_indicators):
            return True

        # If this looks like a report line (starts with spaces + component name)
        if line_lower.strip().startswith(("✅", "  ✅", "     ", "  ok", "  status")):
            return True

        # Configuration/init lines that contain fault keywords but are NOT faults
        config_indicators = [
            "deglitch_enable", "_config", "_init", "_pre_init", "_mode_config",
            "set_nonrst", "set nonrst", "rgu_update_reg", "mtk_wdt_mode",
            "mtk_wdt_pre_init", "mtk_wdt_reset_deglitch",
            "latch_ctl", "req_mode", "req_irq", "debug_ctl",
            "enable crc", "enable spi", "enable debug",
            "pwrap_init", "spmi_read_check", "pmifclkmgr",
            # Normal Android framework messages that contain "denied" etc.
            "servicemanagercppclient", "isdeclared", "ex_security",
            "failed to get isdeclared",
            # Known vendor SELinux denials on stock firmware (not a real fault)
            "vendor_goodix_prop", "vendor_fingerprint", "hal_fingerprint",
            "persist.vendor.fingerprint", "disable.study",
        ]
        if any(c in line_lower for c in config_indicators):
            return True

        return False

    @staticmethod
    def _adjust_confidence(rule: FaultRule, matched_text: str, source: str) -> float:
        """Adjust base confidence based on match quality."""
        conf = rule.confidence
        # Boost if matched in the expected source
        if rule.pattern_source != "any" and source == rule.pattern_source:
            conf = min(1.0, conf + 0.05)
        # Slight penalty if found in a different source
        elif rule.pattern_source != "any" and source != rule.pattern_source:
            conf = max(0.0, conf - 0.10)
        return round(conf, 2)


